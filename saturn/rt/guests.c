/* Bonus characters: the guest table and the stage file selector (see guests.h). SAT_GUESTS builds only. */
#include "guests.h"
const SatGuest sat_guests[] = {
    { "WOLVERINE", 2, 1 },       /* Marvel Super Heroes vs. Street Fighter; Schaefer's slot (owner 11-08) */
    { "MEGA MAN", 4, 2 },        /* Marvel vs. Capcom; Predator Hunter's slot (lane avp-megaman) */
};
const int sat_guest_count = sizeof sat_guests / sizeof sat_guests[0];
const char *const sat_guest_row_names[] = { "OFF", "WOLVERINE", "MEGA MAN", "BOTH" };
const int sat_guest_row_n = 4;
#ifndef SAT_GUEST_DEFAULT
#define SAT_GUEST_DEFAULT 0   /* OFF; a test build may start with a guest on (-DSAT_GUEST_DEFAULT=1) */
#endif
unsigned char sat_guest_sel = SAT_GUEST_DEFAULT;

/* guest_file[g][row][variant]: file number, 0 = no guest file (the arcade's file is used). Generated by saturn/rt/build.py. */
#include "guest_files.inc"

int sat_guest_slots(void)
{
    int i, m = 0;
    for (i = 0; i < sat_guest_count; i++) if (sat_guest_sel & sat_guests[i].sel_bit) m |= sat_guests[i].slot_mask;
    return m;
}

int sat_guest_file(int row, int chars, int variant, int arcade_file)
{
    int i, f;
    for (i = 0; i < sat_guest_count && i < GUEST_ROWS; i++) {
        /* A stage file needs the guest's slot in play; the front end (row 0) holds the select screen and the ranking, which show
           every slot, so a guest with art for them has a front file of its own. */
        if (!(sat_guest_sel & sat_guests[i].sel_bit) || (row && !(chars & sat_guests[i].slot_mask))) continue;
        f = guest_file[i][row][variant];
        if (f) return f;
    }
    return arcade_file;
}

/* Select screen and HUD colours: tables of the arcade's palettes in the program ROM image (guest_pal.h), written for a guest while its art
   is what the loaded file holds. Called after every round file load (kernel.c, which also restores ROM pages), and at boot. */
#include "guest_pal.h"
#include "guest_hudpal.inc"   /* guest_pal[], GUEST_PAL_N: tools/wolverine/hud_art.py; empty without guest art */
extern unsigned char *PAGE[256];
void sat_guest_loaded(int row, int chars, int variant, int file)
{
    unsigned art = 0;
    int i;
    for (i = 0; i < sat_guest_count && i < GUEST_ROWS; i++)
        if ((sat_guest_sel & sat_guests[i].sel_bit) && file && guest_file[i][row][variant] == file && (!row || (chars & sat_guests[i].slot_mask)))
            art |= 1u << i;
    if (GUEST_PAL_N) guest_pal_sync(guest_pal, GUEST_PAL_N, art, (volatile unsigned char *)PAGE[0]);
}

/* Drawing (phase 2): the game's sprite origin routine (0xaa59a, game_bind.c) runs once per sprite group with the actor in a4 and the
   object write pointer in a1; sat_guest_group() notes where each group starts. At the snapshot, sat_guest_objects() swaps a guest slot's
   player body groups for the guest's own pose (per-guest draw functions, weak: a guest without one keeps the AvP character's look). */
typedef unsigned char gu8;
typedef unsigned long gu32;
extern int sat_guest_megaman_draw(gu8 *out, int room, gu32 actor, int ax, int bottom, unsigned short xhi, unsigned short ahi) __attribute__((weak));
extern void sat_guest_megaman_palette(gu8 *page0) __attribute__((weak));
/* Wolverine's whole-list pass (saturn/guests/wolverine/wolverine.c, built with -Dsat_guest_objects=sat_guest_wolverine_objects) */
extern int sat_guest_wolverine_objects(gu8 *obj, int count, int max, gu8 *pal0) __attribute__((weak));
__attribute__((weak)) int sat_guest_touched;
extern gu8 *PAGE[256];
#define GROUPS 96
static struct { unsigned short at; gu32 actor; } grp[GROUPS];
static int ngrp;

void sat_guest_group(gu32 actor, gu32 objptr)
{
    unsigned at = (unsigned)((objptr - 0x708000UL) >> 3);
    if (at >= 0x400) return;
    if (ngrp && grp[ngrp - 1].at >= at) ngrp = 0;   /* the game began a new list */
    if (ngrp < GROUPS) { grp[ngrp].at = (unsigned short)at; grp[ngrp].actor = actor & 0xffffffUL; ngrp++; }
}

static int (*guest_draw(gu32 actor))(gu8 *, int, gu32, int, int, unsigned short, unsigned short)
{
    int kind, i;
    if (actor < 0xff8380UL || actor >= 0xff8680UL || (actor & 0xff) != 0x80) return 0;
    kind = PAGE[0xff][(actor + 0xd2) & 0xffff] & 3;   /* +0xd2: character, the ff81cc bit index */
    for (i = 0; i < sat_guest_count; i++)
        if ((sat_guest_sel & sat_guests[i].sel_bit) && sat_guests[i].slot_mask == (1 << kind)) {
            if (sat_guests[i].slot_mask == 4) return sat_guest_megaman_draw;
            return 0;
        }
    return 0;
}

/* The player gun shot pool (tag +8 = 4 from ff8680, class +2 = 0, owner word +0x26; MAME, tools/megaman/avp_shot.lua): a Mega Man player's
   shot keeps hitting through the game's own path but is not drawn; his Mega Buster shot is drawn with his pose instead. */
static int is_guest_shot(gu32 actor)
{
    gu8 *b = PAGE[0xff];
    gu32 o = actor & 0xffff, owner;
    if ((actor >> 16) != 0xff || o < 0x8680 || o >= 0x9580 || b[o + 8] != 4 || b[o + 2] != 0) return 0;
    owner = 0xff0000UL | ((gu32)b[o + 0x26] << 8) | b[o + 0x27];
    return guest_draw(owner) == sat_guest_megaman_draw && sat_guest_megaman_draw;
}

/* Wolverine has no gun: a Wolverine player's shots and the muzzle flash are not drawn. Berserker Barrage takes the gun's state slot
   (saturn/guests/wolverine/wolverine.c). Yaba, stage 02, 11-08: a shot is a tag +8 = 4 actor (+2 = 5 while alive) in ff8680.. with the owner's
   block word at +0x26; the muzzle flash is a tag 0x24 actor (+2 = 4, +3 = 1) in ffe080..ffe17f with the owner word at +0x28. The shots also do
   no damage (the collision passes refuse them, game_bind.c). */
static int is_wolverine_shot(gu32 actor)
{
    gu8 *b = PAGE[0xff];
    gu32 o = actor & 0xffff, owner;
    if (!(sat_guest_sel & 1) || (actor >> 16) != 0xff || o < 0x8600 || o >= 0xe400) return 0;
    if (b[o + 8] == 4) owner = ((gu32)b[o + 0x26] << 8) | b[o + 0x27];
    else if (b[o + 8] == 0x24) owner = ((gu32)b[o + 0x28] << 8) | b[o + 0x29];
    else return 0;
    if (owner < 0x8380 || owner >= 0x8580 || (owner & 0xff) != 0x80) return 0;
    return b[owner] != 0 && (b[owner + 0xd2] & 3) == 1;   /* +0xd2 character: 1 Schaefer, whose slot Wolverine takes */
}
static int no_draw(gu8 *out, int room, gu32 actor, int ax, int bottom, unsigned short xhi, unsigned short ahi)
{
    (void)out; (void)room; (void)actor; (void)ax; (void)bottom; (void)xhi; (void)ahi;
    return 0;
}

static int be16(const gu8 *p) { return (p[0] << 8) | p[1]; }

/* obj: the snapshot's copy of the object list (count entries, room for max). page0: the snapshot's sprite palette page. Returns the new count. */
int sat_guest_objects(gu8 *obj, int count, int max, gu8 *page0)
{
    int g, used = 0, shift = 0, wv = 0;
    if (!sat_guest_sel) return count;
    if (sat_guest_megaman_palette && (sat_guest_sel & 2)) sat_guest_megaman_palette(page0);
    for (g = 0; g < ngrp; g++) {
        int (*draw)(gu8 *, int, gu32, int, int, unsigned short, unsigned short) = guest_draw(grp[g].actor);
        int shot = 0;
        if (!draw && sat_guest_megaman_draw && is_guest_shot(grp[g].actor)) { draw = sat_guest_megaman_draw; shot = 1; }
        if (!draw && is_wolverine_shot(grp[g].actor)) { draw = no_draw; shot = 1; }
        int s = grp[g].at + shift, e = g + 1 < ngrp ? grp[g + 1].at + shift : count, i, x0 = 0, x1 = 0, bottom = -1000, n, room;
        int bx;
        gu8 tmp[8 * 96];
        if (!draw || s >= count) continue;
        if (e > count) e = count;
        bx = be16(obj + s * 8) & 0x3ff;
        for (i = s; i < e; i++) {   /* the body's entries: near the first one (HUD words written by other routines are not) */
            const gu8 *o = obj + i * 8;
            int x = be16(o) & 0x3ff, y = be16(o + 2) & 0x3ff, a = be16(o + 6);
            int h = (((a >> 12) & 15) + 1) * 16, d = (x - bx) & 0x3ff;
            if (d > 160 && d < 1024 - 160) break;
            if (y + h > bottom) bottom = y + h;
        }
        e = i;
        if (shot || used & (1 << (((grp[g].actor - 0xff8380UL) >> 8) & 3))) {   /* weapon or extra groups of the same body, or its gun shot: drop */
            n = 0;
        } else {
            for (i = s; i < e; i++) {
                const gu8 *o = obj + i * 8;
                int x = be16(o) & 0x3ff, y = be16(o + 2) & 0x3ff, a = be16(o + 6);
                int w = (((a >> 8) & 15) + 1) * 16, h = (((a >> 12) & 15) + 1) * 16;
                if (y + h <= bottom - 32) continue;
                if (!x1 || x < x0) x0 = x;
                if (!x1 || x + w > x1) x1 = x + w;
            }
            n = draw(tmp, 96, grp[g].actor, (x0 + x1) / 2, bottom, (unsigned short)(be16(obj + s * 8) & 0xfc00), (unsigned short)(be16(obj + s * 8 + 6) & 0x80));
            used |= 1 << (((grp[g].actor - 0xff8380UL) >> 8) & 3);
        }
        /* replace entries s..e-1 by the n new ones, shifting the rest */
        room = max - count + (e - s);
        if (n > room) n = room;
        if (n != e - s) {
            gu8 *src = obj + e * 8, *dst = obj + (s + n) * 8;
            int bytes = (count - e) * 8, k;
            if (dst < src) for (k = 0; k < bytes; k++) dst[k] = src[k];
            else for (k = bytes - 1; k >= 0; k--) dst[k] = src[k];
        }
        for (i = 0; i < n * 8; i++) obj[s * 8 + i] = tmp[i];
        count += n - (e - s);
        shift += n - (e - s);
    }
    /* Wolverine's pass works on the whole list by palette and place, so it runs after the group-indexed guests */
    if (sat_guest_wolverine_objects) { count = sat_guest_wolverine_objects(obj, count, max, page0); wv = sat_guest_touched; }
    sat_guest_touched = wv || (sat_guest_megaman_palette && (sat_guest_sel & 2));
    return count;
}

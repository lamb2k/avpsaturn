/* Bonus characters: the guest table and the stage file selector (see guests.h). SAT_GUESTS builds only. */
#include "guests.h"
const SatGuest sat_guests[] = {
    { "WOLVERINE", 2, 1 },       /* Marvel Super Heroes vs. Street Fighter; Schaefer's slot (owner 11-08) */
    { "MEGA MAN", 4, 2 },        /* Marvel vs. Capcom; Predator Hunter's slot (lane avp-megaman) */
};
const int sat_guest_count = sizeof sat_guests / sizeof sat_guests[0];
const char *const sat_guest_row_names[] = { "OFF", "WOLVERINE", "MEGA MAN", "BOTH" };
const int sat_guest_row_n = 4;
unsigned char sat_guest_sel;

/* guest_file[g][row][variant]: file number, 0 = no guest file (the arcade's file is used). Generated by saturn/rt/build.py. */
#include "guest_files.inc"

int sat_guest_slots(void)
{
    int i, m = 0;
    for (i = 0; i < sat_guest_count; i++) if (sat_guest_sel & sat_guests[i].sel_bit) m |= sat_guests[i].slot_mask;
    return m;
}

int sat_guest_file(int row, int chars, int variant, int arcade_file)
{
    int i, f;
    for (i = 0; i < sat_guest_count && i < GUEST_ROWS; i++) {
        if (!(sat_guest_sel & sat_guests[i].sel_bit) || !(chars & sat_guests[i].slot_mask)) continue;
        f = guest_file[i][row][variant];
        if (f) return f;
    }
    return arcade_file;
}

#!/usr/bin/env python3
"""Generate generated/avsp_scene_ids.h from the tracked scene manifest.

The header is the single checked bridge between the RP6 manifest and the
16-bit AvspSceneDef runtime interface: the pinned source-census SHA-256,
the scene count, the runtime-ID table, the transition-target table, and
named constants for the evidence-labelled scenes. It contains no ROM or
framebuffer bytes (it is generated, and ignored, purely for build-order
symmetry with the other generated inputs).

Every invariant the runtime relies on is enforced here: IDs are
index + 1 in 1..0x7FFF, zero invalid, collision-free; every transition
target resolves to a manifest scene or is the explicit route-end 0.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "data" / "avsp_scene_manifest.json"
OUTPUT = ROOT / "generated" / "avsp_scene_ids.h"


def constant_name(label: str) -> str:
    return "AVSP_SCENE_" + label.upper().replace("-", "_")


def main() -> None:
    manifest = json.loads(MANIFEST.read_text())
    scenes = manifest["scenes"]

    ids = []
    for index, scene in enumerate(scenes):
        rid = scene["runtime_scene_id"]
        if rid != index + 1 or rid == 0 or rid > 0x7FFF:
            raise SystemExit(f"scene {index}: runtime_scene_id {rid} "
                             f"violates the 1..0x7FFF index+1 policy")
        ids.append(rid)
    if len(set(ids)) != len(ids):
        raise SystemExit("duplicate runtime_scene_id")

    targets = []
    valid = set(ids)
    for index, scene in enumerate(scenes):
        target = scene["transition"]["target_runtime_scene_id"]
        if target is None:
            targets.append(0)  # explicit route-end sentinel
        elif target not in valid:
            raise SystemExit(f"scene {index}: transition target {target} "
                             f"does not resolve to a manifest scene")
        else:
            targets.append(target)

    lines = [
        "/* Generated by tools/gen_avsp_scene_ids.py from",
        " * data/avsp_scene_manifest.json. Do not edit, do not commit.",
        " * Contains no ROM or framebuffer bytes. */",
        "#ifndef AVSP_SCENE_IDS_H",
        "#define AVSP_SCENE_IDS_H",
        "",
        f"#define AVSP_SCENE_CENSUS_SHA256 "
        f"\"{manifest['source_census_sha256']}\"",
        f"#define AVSP_SCENE_COUNT {len(scenes)}",
        "",
        "/* runtime_scene_id per route-ordered scene (index + 1, "
        "1..0x7FFF). */",
        "static const unsigned short avsp_scene_runtime_ids"
        f"[{len(scenes)}] = {{",
    ]
    for start in range(0, len(ids), 12):
        lines.append("    " + ", ".join(
            str(i) for i in ids[start:start + 12]) + ",")
    lines += [
        "};",
        "",
        "/* Transition target runtime ID per scene; 0 = route end. */",
        f"static const unsigned short avsp_scene_transition_targets"
        f"[{len(scenes)}] = {{",
    ]
    for start in range(0, len(targets), 12):
        lines.append("    " + ", ".join(
            str(t) for t in targets[start:start + 12]) + ",")
    lines += ["};", "", "/* Evidence-labelled scenes. */"]
    for scene in scenes:
        if scene["label"]:
            lines.append(f"#define {constant_name(scene['label'])} "
                         f"{scene['runtime_scene_id']}")
    lines += ["", "#endif /* AVSP_SCENE_IDS_H */", ""]

    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="ascii", newline="\n")
    labelled = sum(1 for s in scenes if s["label"])
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(scenes)} scenes, "
          f"{labelled} labelled constants, census "
          f"{manifest['source_census_sha256'][:12]}...")


if __name__ == "__main__":
    main()

#!/usr/bin/env python
"""Wolverine's poses, moves and colours as C tables for saturn/guests/wolverine (build time, from tools/wolverine/assets.py remap.json).
Output goes to the build's gen directory (ROM-derived, never in git).
usage: gen_c.py ASSETS_DIR OUT.inc [COLOUR]"""
import json, pathlib, re, sys

A = json.loads((pathlib.Path(sys.argv[1]) / "remap.json").read_text())
out = pathlib.Path(sys.argv[2])
colour = sys.argv[3] if len(sys.argv) > 3 else A["default_colour"]
P, keys = A["poses"], A["keys"]
moves = A.get("moves_one", A["moves"])
if A.get("boxes_pending"):
    raise SystemExit("NO-GO: regenerate boxes.json with boxes.py after pose reselection")
required = {"idle", "walk", "jump", "lp", "hp", "hk", "berserker", "tornado", "knockdown", "throw", "hit_etc", "hit_m", "hit_h", "crouch"}
if required - moves.keys():
    raise SystemExit("NO-GO: missing runtime moves: " + ", ".join(sorted(required - moves.keys())))
for name, steps in moves.items():
    if not re.fullmatch(r"[a-z][a-z0-9_]*", name) or not 1 <= len(steps) <= 256:
        raise SystemExit(f"NO-GO: invalid name or 8-bit step count for {name!r}")
    for pose, frames, _anchor in steps:
        if not isinstance(pose, int) or not 0 <= pose < len(P):
            raise SystemExit(f"NO-GO: invalid pose in {name}")
        if not isinstance(frames, int) or not 1 <= frames <= 255:
            raise SystemExit(f"NO-GO: {name} has a {frames}-tick hold outside WvStep's 1..255 range; retain more poses")
    if sum(step[1] for step in steps) > 65535:
        raise SystemExit(f"NO-GO: {name} exceeds the 16-bit move clock")
used = sorted({x[0] for m in moves.values() for x in m})
if len(used) > 256 or sum(map(len, moves.values())) > 65535:
    raise SystemExit("NO-GO: pose or step table index would overflow")
pid = {p: i for i, p in enumerate(used)}
if "stance_pose" in A and A["stance_pose"] not in pid:
    raise SystemExit("NO-GO: the ready stance must be retained in moves_one")
required_keys = {keys[tile[2]] for pose in used for tile in P[pose]}
for stage, stage_keys in A.get("stage_keys", {}).items():
    missing = required_keys - set(stage_keys)
    if missing:
        raise SystemExit(f"NO-GO: stage {stage} omits {len(missing)} emitted-pose tiles; rerun reselect.py")
ent, start = [], [0]
for p in used:
    for dx, dy, t, hf, vf, prow in P[p]:
        if not (-32768 <= dx <= 32767 and -32768 <= dy <= 32767 and
                0 <= keys[t] <= 65535 and hf in (0, 1) and vf in (0, 1) and prow in (0, 1)):
            raise SystemExit("NO-GO: tile field exceeds the runtime representation")
        ent.append(f"{{{dx},{dy},{keys[t]},{hf | vf << 1 | prow << 2}}}")
    start.append(len(ent))
seq, mstart, names = [], [0], []
for m, s in moves.items():
    names.append(m)
    for p, n, _ in s:
        seq.append(f"{{{pid[p]},{n}}}")
    mstart.append(len(seq))
if len(ent) > 65535:
    raise SystemExit("NO-GO: tile-entry index would overflow")
pal = []
for row in A["colours"][colour]:
    for r, g, b in row:
        pal.append(0xf000 | (r >> 4) << 8 | (g >> 4) << 4 | b >> 4)
if len(pal) != 32:
    raise SystemExit("NO-GO: Wolverine requires exactly two 16-colour palette rows")
lines = [
    "/* Generated by tools/wolverine/gen_c.py from the user's MSHvSF set: do not commit. */",
    "typedef struct { short dx, dy; unsigned short key; unsigned char flags; } WvTile;   /* flags: 1 hflip, 2 vflip, 4.. palette row */",
    "typedef struct { unsigned char pose, frames; } WvStep;",
    f"#define WV_POSES {len(used)}",
    f"#define WV_STANCE {pid.get(A.get('stance_pose', 17), 65535)}   /* pose id of the ready stance; 65535 is outside an 8-bit pose */",
    f"static const WvTile wv_tiles[{len(ent)}] = {{{','.join(ent)}}};",
    f"static const unsigned short wv_pose_start[{len(start)}] = {{{','.join(map(str, start))}}};",
    f"static const WvStep wv_steps[{len(seq)}] = {{{','.join(seq)}}};",
    f"static const unsigned short wv_move_start[{len(mstart)}] = {{{','.join(map(str, mstart))}}};",
    "enum { " + ", ".join(f"WV_{m.upper()}" for m in names) + ", WV_MOVES };",
    f"static const unsigned short wv_pal[{len(pal)}] = {{{','.join(hex(c) for c in pal)}}};",
]
# Per-move numbers of the host game's driver, one table (a native Wolverine update would reuse it and swap only the driver):
# native ticks of Schaefer's state that shows the move (MSHvSF holds stretch them: schaefer_states.lua, 11-08; gun 02000c measured on Yaba),
# and his attack chain (the stage -> move of each new attack of a chain; light, light, heavy, kick finisher).
NATIVE = dict(lp=15, hp=15, hk=32, berserker=30, tornado=57)
CHAIN = ("lp", "lp", "hp", "hk")
NATIVE.update(A.get("native", {}))
CHAIN = tuple(A.get("chain", CHAIN))
if any(m not in moves for m in CHAIN) or len(CHAIN) != 4:
    raise SystemExit("NO-GO: the attack chain needs four stages naming resident moves")
# Height above his standing feet line per step, from and to (pixels, the pose is drawn this much higher; interpolated across the step by the runtime).
# Poses are anchored by their own bottom row, so a jump, which MSHvSF draws in the air, needs it; zero for every other move.
LIFT = A.get("lift", {})
lift = []
for m, s_ in moves.items():
    ls = LIFT.get(m, [])
    if ls and len(ls) != len(s_):
        raise SystemExit(f"NO-GO: lift table of {m} does not match its steps")
    for k in range(len(s_)):
        a, b = ls[k] if ls else (0, 0)
        if not (0 <= a <= 255 and 0 <= b <= 255):
            raise SystemExit("NO-GO: lift outside 0..255")
        lift += [a, b]
lines += [
    f"static const unsigned char wv_lift[{len(lift)}] = {{{','.join(map(str, lift))}}};",
]
# Ground speed of his walk against Schaefer's, in 1/16 (16 = as Schaefer): AvP's walk is about 2.0 px a tick (Yaba, stage 02, 290 held frames, 1.8-2.2),
# MSHvSF's about 2.8 px a frame (origin of boxcap/boxes.txt over frames 2005-2060): 22 is 1.375. Depth moves scale the same. His slot only.
SPEED = dict(walk=22)
SPEED.update(A.get("speed", {}))
lines += [
    "static const unsigned char wv_speed_tab[WV_MOVES] = {" + ",".join(str(SPEED.get(m, 16)) for m in names) + "};",
    "static const unsigned char wv_nat_tab[WV_MOVES] = {" + ",".join(str(NATIVE.get(m, 0)) for m in names) + "};",
    "static const unsigned char wv_chain_tab[4] = {" + ",".join("WV_" + m.upper() for m in CHAIN) + "};",
]
# Boxes per move step (tools/wolverine/boxes.py -> boxes.json beside remap.json): centre and half size, x forward and y up of his feet.
# WvBox: hit x, hit half w, hit y, hit half h, hurt x, hurt half w, hurt y, hurt half h; hit half w 0 = no hit box on that step.
bj = pathlib.Path(sys.argv[1]) / "boxes.json"
B = json.loads(bj.read_text()) if bj.exists() else {}
if B:
    for name, steps in moves.items():
        boxes = B.get(name, [])
        if len(boxes) != len(steps) or any(box.get("frames", step[1]) != step[1] for box, step in zip(boxes, steps)):
            raise SystemExit(f"NO-GO: stale box steps for {name}; rerun boxes.py")
def cw(r):
    if not r:
        return (0, 0, 0, 0)
    c = lambda a, b: max(-128, min(127, (a + b) // 2))
    h = lambda a, b: max(1, min(255, (b - a + 1) // 2))
    return (c(r[0], r[1]), h(r[0], r[1]), c(r[2], r[3]), h(r[2], r[3]))
bx = []
for m, s in moves.items():
    bs = B.get(m, [])
    for k in range(len(s)):
        st = bs[k] if k < len(bs) else {}
        bx.append("{%d,%d,%d,%d,%d,%d,%d,%d}" % (cw(st.get("hit")) + cw(st.get("hurt"))))
lines += [
    "typedef struct { signed char hx; unsigned char hw; signed char hy; unsigned char hh; signed char ux; unsigned char uw; signed char uy; unsigned char uh; } WvBox;",
    f"#define WV_HAVE_BOXES {1 if B else 0}",
    f"static const WvBox wv_box[{len(bx)}] = {{{','.join(bx)}}};",
]
out.write_text("\n".join(lines) + "\n")
print("poses", len(used), "tiles", len(ent), "steps", len(seq), "bytes ~", len(ent) * 8 + len(seq) * 2 + len(pal) * 2)

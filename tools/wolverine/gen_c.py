#!/usr/bin/env python
"""Wolverine's poses, moves and colours as C tables for saturn/guests/wolverine (build time, from tools/wolverine/assets.py remap.json).
Output goes to the build's gen directory (ROM-derived, never in git).
usage: gen_c.py ASSETS_DIR OUT.inc [COLOUR]"""
import json, pathlib, sys

A = json.loads((pathlib.Path(sys.argv[1]) / "remap.json").read_text())
out = pathlib.Path(sys.argv[2])
colour = sys.argv[3] if len(sys.argv) > 3 else A["default_colour"]
P, keys = A["poses"], A["keys"]
moves = A.get("moves_one", A["moves"])
used = sorted({x[0] for m in moves.values() for x in m})
pid = {p: i for i, p in enumerate(used)}
ent, start = [], [0]
for p in used:
    for dx, dy, t, hf, vf, prow in P[p]:
        ent.append(f"{{{dx},{dy},{keys[t]},{hf | vf << 1 | prow << 2}}}")
    start.append(len(ent))
seq, mstart, names = [], [0], []
for m, s in moves.items():
    names.append(m)
    for p, n, _ in s:
        seq.append(f"{{{pid[p]},{n}}}")
    mstart.append(len(seq))
pal = []
for row in A["colours"][colour]:
    for r, g, b in row:
        pal.append(0xf000 | (r >> 4) << 8 | (g >> 4) << 4 | b >> 4)
lines = [
    "/* Generated by tools/wolverine/gen_c.py from the user's MSHvSF set: do not commit. */",
    "typedef struct { short dx, dy; unsigned short key; unsigned char flags; } WvTile;   /* flags: 1 hflip, 2 vflip, 4.. palette row */",
    "typedef struct { unsigned char pose, frames; } WvStep;",
    f"#define WV_POSES {len(used)}",
    f"#define WV_STANCE {pid.get(A.get('stance_pose', 17), 255)}   /* pose id of the ready stance after an attack */",
    f"static const WvTile wv_tiles[{len(ent)}] = {{{','.join(ent)}}};",
    f"static const unsigned short wv_pose_start[{len(start)}] = {{{','.join(map(str, start))}}};",
    f"static const WvStep wv_steps[{len(seq)}] = {{{','.join(seq)}}};",
    f"static const unsigned short wv_move_start[{len(mstart)}] = {{{','.join(map(str, mstart))}}};",
    "enum { " + ", ".join(f"WV_{m.upper()}" for m in names) + ", WV_MOVES };",
    f"static const unsigned short wv_pal[{len(pal)}] = {{{','.join(hex(c) for c in pal)}}};",
]
# Boxes per move step (tools/wolverine/boxes.py -> boxes.json beside remap.json): centre and half size, x forward and y up of his feet.
# WvBox: hit x, hit half w, hit y, hit half h, hurt x, hurt half w, hurt y, hurt half h; hit half w 0 = no hit box on that step.
bj = pathlib.Path(sys.argv[1]) / "boxes.json"
B = json.loads(bj.read_text()) if bj.exists() else {}
def cw(r):
    if not r:
        return (0, 0, 0, 0)
    c = lambda a, b: max(-128, min(127, (a + b) // 2))
    h = lambda a, b: max(1, min(255, (b - a + 1) // 2))
    return (c(r[0], r[1]), h(r[0], r[1]), c(r[2], r[3]), h(r[2], r[3]))
bx = []
for m, s in moves.items():
    bs = B.get(m, [])
    for k in range(len(s)):
        st = bs[k] if k < len(bs) else {}
        bx.append("{%d,%d,%d,%d,%d,%d,%d,%d}" % (cw(st.get("hit")) + cw(st.get("hurt"))))
lines += [
    "typedef struct { signed char hx; unsigned char hw; signed char hy; unsigned char hh; signed char ux; unsigned char uw; signed char uy; unsigned char uh; } WvBox;",
    f"#define WV_HAVE_BOXES {1 if B else 0}",
    f"static const WvBox wv_box[{len(bx)}] = {{{','.join(bx)}}};",
]
out.write_text("\n".join(lines) + "\n")
print("poses", len(used), "tiles", len(ent), "steps", len(seq), "bytes ~", len(ent) * 8 + len(seq) * 2 + len(pal) * 2)

#!/usr/bin/env python
"""Build the gameplay patch table of the native Wolverine (plan section 4.2): reads the ROM image and tools/wolverine/native_patch.json, writes
gen/wv_patch.inc (private, ROM-derived: holds the original bytes, so nothing needs a RAM backup at run time).

The runtime (wolverine.c) is stateless: for each entry it writes `now` over `orig` and `orig` back over `now`, and refuses (counts) any other byte
pattern, so a re-applied or half-restored image is detected rather than patched blindly. A patched address must sit on a ROM page that every
stage file for the replaced slot keeps (rounds.json keep_pages): a page a stage drops holds spilled tile data and must never be written.

usage: nativepatch.py ROM.bin rounds.json native_patch.json OUT.inc"""
import json
import pathlib
import sys

rom = pathlib.Path(sys.argv[1]).read_bytes()
R = json.loads(pathlib.Path(sys.argv[2]).read_text())
spec = json.loads(pathlib.Path(sys.argv[3]).read_text())["patches"]
page = R["page"]
# every stage file that can be loaded with the replaced slot in play (the arcade files and the guest variants) must keep the page
bad_pages = {}
rows = []
for p in spec:
    a, n, v = int(p["addr"], 16), p["len"], int(p["value"], 16)
    assert n == 2, p   # 16-bit duration words
    orig = rom[a:a + n]
    new = v.to_bytes(n, "big")
    assert orig != new, "patch %s changes nothing" % p["name"]
    for q in range(a // page, (a + n - 1) // page + 1):
        miss = [f["name"] for f in R["files"] if f.get("keep_pages") is not None and q not in set(f["keep_pages"])]
        if miss:
            bad_pages[p["name"]] = miss[:4]
    rows.append((a, n, orig, new, p["name"]))
if bad_pages:
    raise SystemExit("NO-GO: a patch lies on a page some stage file drops: " + json.dumps(bad_pages))
ov = sorted(rows)
for x, y in zip(ov, ov[1:]):
    assert x[0] + x[1] <= y[0], "overlapping patches %s %s" % (x[4], y[4])
out = ["/* Generated by tools/wolverine/nativepatch.py: do not commit. */\n",
       "typedef struct { unsigned long addr; unsigned short orig, now; } WvPatch;\n",
       "#define WV_PATCHES %d\n" % len(rows),
       "static const WvPatch wv_patch_tab[WV_PATCHES] = {\n"]
for a, n, o, w, name in rows:
    out.append("    {0x%x, 0x%04x, 0x%04x},   /* %s */\n" % (a, int.from_bytes(o, "big"), int.from_bytes(w, "big"), name))
out.append("};\n")
pathlib.Path(sys.argv[4]).write_text("".join(out))
print("patches", len(rows))

#!/usr/bin/env python
"""Fork generator for the native Wolverine (docs/notes/AVP_WOLVERINE_NATIVE_PLAN_20261109.md, section 4).

Extracts Schaefer's character-private routines from the generated lifted sources, at build time, and writes them back as renamed copies
wvf_<addr> plus a wrapper f_<addr> for each entry routine:

    void f_24454(void) { if (sat_wv_fork_on(a6, ID)) wvf_24454(); else lifted_24454(); }

The original body is kept whole as lifted_<addr> (build.py GUEST_WRAP; the host runner's apply step renames it the same way), so a
default-off or non-Wolverine call takes the lifted code. Nothing ROM-derived is committed: the repository holds this generator and the
list of routine addresses only; the output file lives in the work directory.

The entry routines are the nine Schaefer-private routines of the ROM's character-indexed dispatch tables (plan section 1.2). A fork also
copies its private callees (functions inside Schaefer's address range whose every caller is in the fork set), so the clone is closed.
Shared routines stay shared: calls to them are unchanged.

usage (library): build(sources, ids) -> ForkResult
usage (CLI):     forkgen.py SRC_DIR OUT.c [--ids 0,1] [--host] [--check]
  SRC_DIR holds c*.c (the target build passes WORK/gen after build.py rewrote OP reads; the host passes the lifter's output).
"""
import argparse
import pathlib
import re
import sys

# id, address, role (plan section 1.2). The id is the bit in the runtime fork mask.
ENTRIES = [
    (0, 0x24454, "attack"),
    (1, 0x24f04, "special"),
    (2, 0x2539e, "jump"),
    (3, 0x2501e, "slot0a"),
    (4, 0x2576a, "gun"),
    (5, 0x255fa, "pretick"),
    (6, 0x24c64, "action14"),
    (7, 0x24582, "held"),
    (8, 0x2f70, "table19c7a"),
]
SHIP_IDS = (0, 1)                       # shipping fork: attack and special
ALL_IDS = tuple(e[0] for e in ENTRIES)  # diagnostic clone
PRIVATE_LO, PRIVATE_HI = 0x24400, 0x25a00   # Schaefer's block; Hunter's routines start at 0x25b14

FUNC = re.compile(r"((?:^#define [a-z]\d \(R->[ad]\[\d\]\)\n)*)^void f_([0-9a-f]+)\(void\)\{(.*?)^\}\n((?:^#undef [a-z]\d\n)*)", re.M | re.S)
CALL = re.compile(r"\bf_([0-9a-f]+)\(\)")


class ForkResult:
    def __init__(self):
        self.text = ""
        self.wrapped = []     # entry addresses whose original must be renamed lifted_<addr>
        self.copied = []      # every address copied (entries and private callees)
        self.entry_ids = {}   # address -> id
        self.callees_missing = []


def parse(sources):
    """sources: {name: text}. Returns {addr: (chunk name, match)} and the common prologue."""
    funcs, prologue = {}, None
    for name, t in sources.items():
        m = re.search(r"^extern void f_[0-9a-f]+\(void\);", t, re.M)
        p = t[:m.start()]
        if prologue is None:
            prologue = p
        elif prologue != p:
            raise SystemExit(f"forkgen: prologue of {name} differs from the first chunk")
        for fm in FUNC.finditer(t):
            funcs[int(fm.group(2), 16)] = (name, fm)
    return funcs, prologue


def closure(funcs, ids):
    entries = {a for i, a, _ in ENTRIES if i in ids}
    missing = [hex(a) for a in entries if a not in funcs]
    if missing:
        raise SystemExit("forkgen: entry routines not found in the lifted sources: " + ",".join(missing))
    callers = {}
    for a, (_, fm) in funcs.items():
        for c in CALL.findall(fm.group(3)):
            callers.setdefault(int(c, 16), set()).add(a)
    every_entry = {a for _, a, _ in ENTRIES}
    S = set(entries)
    changed = True
    while changed:
        changed = False
        for a in sorted(S):
            for c in CALL.findall(funcs[a][1].group(3)):
                c = int(c, 16)
                if c in S or c not in funcs or c in every_entry or not PRIVATE_LO <= c < PRIVATE_HI:
                    continue
                if callers.get(c, set()) <= S:
                    S.add(c)
                    changed = True
    return entries, S


def build(sources, ids, count=True):
    """sources: {chunk name: text}; ids: fork ids to copy. Returns a ForkResult."""
    funcs, prologue = parse(sources)
    entries, S = closure(funcs, ids)
    res = ForkResult()
    by_addr = {a: i for i, a, _ in ENTRIES}
    S_sorted = sorted(S)
    called = set()
    body = []
    for a in S_sorted:
        d, b, u = funcs[a][1].group(1), funcs[a][1].group(3), funcs[a][1].group(4)
        t = "void wvf_%x(void){%s}\n" % (a, b)
        for c in set(CALL.findall(t)):
            ci = int(c, 16)
            called.add(ci)
            if ci in S:
                t = re.sub(r"\bf_%s\(\)" % c, "wvf_%s()" % c, t)
        body.append(d + t + u)
    out = ["/* Generated by tools/wolverine/forkgen.py from the lifted sources. ROM-derived: never commit. */\n", prologue]
    ext = sorted(c for c in called if c not in S)
    out += ["extern void f_%x(void);\n" % c for c in ext]
    out.append("extern int sat_wv_fork_on(unsigned long a6, int id);\n")
    if count:
        out.append("#ifdef SAT_WV_FORK_COUNT\nunsigned sat_wv_fork_calls[%d];\n#endif\n" % len(ENTRIES))
    out += ["void wvf_%x(void);\n" % a for a in S_sorted]
    out += body
    out.append("#define a6 (R->a[6])\n")
    for a in sorted(entries):
        i = by_addr[a]
        out.append("extern void lifted_%x(void);\n" % a)
        cnt = "#ifdef SAT_WV_FORK_COUNT\nsat_wv_fork_calls[%d]++;\n#endif\n" % i if count else ""
        out.append("void f_%x(void){\nif (sat_wv_fork_on(a6, %d)) {\n%s wvf_%x();\n} else lifted_%x();\n}\n" % (a, i, cnt, a, a))
    out.append("#undef a6\n")
    res.text = "".join(out)
    res.wrapped = sorted(entries)
    res.copied = S_sorted
    res.entry_ids = {a: by_addr[a] for a in entries}
    return res


def wrapped_names(ids):
    """Entry addresses (hex without 0x) whose lifted body build.py must keep as lifted_<addr>."""
    return tuple("%x" % a for i, a, _ in ENTRIES if i in ids)


def check_textual_identity(sources, res):
    """Build-time proof by construction: every fork body equals its original with only the names changed."""
    funcs, _ = parse(sources)
    bad = []
    for a in res.copied:
        orig = funcs[a][1].group(3)
        mm = re.search(r"^void wvf_%x\(void\)\{(.*?)^\}\n" % a, res.text, re.M | re.S)
        if not mm:
            bad.append(hex(a))
            continue
        fork = re.sub(r"\bwvf_([0-9a-f]+)\(\)", r"f_\1()", mm.group(1))
        if fork != orig:
            bad.append(hex(a))
    return bad


def read_sources(d):
    return {p.name: p.read_text() for p in sorted(pathlib.Path(d).glob("c[0-9]*.c"), key=lambda p: int(p.stem[1:]))}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src")
    ap.add_argument("out")
    ap.add_argument("--ids", default="all")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    ids = ALL_IDS if a.ids == "all" else tuple(int(x) for x in a.ids.split(","))
    s = read_sources(a.src)
    r = build(s, ids)
    pathlib.Path(a.out).write_text(r.text)
    print("copied", len(r.copied), "entries", ",".join(hex(x) for x in r.wrapped), "bytes", len(r.text))
    print("private callees", ",".join(hex(x) for x in r.copied if x not in r.entry_ids))
    if a.check:
        bad = check_textual_identity(s, r)
        print("textual identity", "OK" if not bad else "FAIL " + ",".join(bad))
        return 1 if bad else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())

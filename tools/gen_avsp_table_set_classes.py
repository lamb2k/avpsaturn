#!/usr/bin/env python3
"""Generate the native class-to-collision-table lookup from checked evidence.

The input and tracked outputs contain addresses and decoded constants only. The
generated C header is build output and contains no ROM bytes.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = ROOT / "data" / "avsp_table_set_states.json"
DEFAULT_OUTPUT = ROOT / "generated" / "avsp_table_set_classes.h"


def parse_hex(value: str, label: str) -> int:
    try:
        parsed = int(value, 16)
    except (TypeError, ValueError) as exc:
        raise SystemExit(f"{label}: expected a hexadecimal string, got {value!r}") from exc
    return parsed


def generate(source: Path, output: Path) -> None:
    document = json.loads(source.read_text(encoding="utf-8"))
    if document.get("schema") != 3 or document.get("result") != "PASS":
        raise SystemExit("table-set evidence must be the checked schema-3 PASS manifest")

    rows: list[tuple[int, int]] = []
    for class_text, item in sorted(document["street_classes"].items()):
        class_id = parse_hex(class_text, "class id")
        table_set = parse_hex(item["state0_store"]["value"], f"{class_text} table_set")
        if not 0 <= class_id <= 0xFF:
            raise SystemExit(f"class id out of range: {class_text}")
        rows.append((class_id, table_set))

    if len(rows) != 3 or len({class_id for class_id, _ in rows}) != len(rows):
        raise SystemExit("expected exactly three unique checked street classes")

    lines = [
        "/* Generated by tools/gen_avsp_table_set_classes.py. Do not edit or commit. */",
        "#ifndef AVSP_TABLE_SET_CLASSES_GENERATED_H",
        "#define AVSP_TABLE_SET_CLASSES_GENERATED_H",
        "",
        "typedef struct {",
        "    unsigned char class_id;",
        "    unsigned long table_set;",
        "} AvspClassTableSet;",
        "",
        "static const AvspClassTableSet avsp_class_table_sets[] = {",
    ]
    for class_id, table_set in rows:
        lines.append(f"    {{ 0x{class_id:02X}u, 0x{table_set:08X}uL }},")
    lines.extend(
        [
            "};",
            "static const unsigned short avsp_class_table_set_count =",
            "    (unsigned short)(sizeof(avsp_class_table_sets) / sizeof(avsp_class_table_sets[0]));",
            "",
            "#endif /* AVSP_TABLE_SET_CLASSES_GENERATED_H */",
            "",
        ]
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="ascii", newline="\n")
    print(f"generated {output.relative_to(ROOT)}: {len(rows)} checked classes")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    generate(args.input, args.output)


if __name__ == "__main__":
    main()

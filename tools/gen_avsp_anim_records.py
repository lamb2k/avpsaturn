"""Extract the animation-record spans the runtime needs onto the disc.

The Saturn build cannot carry the arcade program image, so it carries only the
pose records the game actually reaches, each keeping its original source
address. The interpreter (`avsp_anim_script.c`) resolves reads by address, so it
behaves identically over the extracted spans and over the full image - which is
exactly what `tests/avsp_anim_walk_test.c` checks by running both and requiring
identical counters.

Reachability, not guesswork, decides what is extracted:

  seeds  every distinct animation-record pointer (`actor +0x1C`) observed for a
         live actor in the work-RAM captures;
  walk   from each seed, follow the script's own control flow - a record is 16
         bytes and advances to +16, unless flags bit 15 is set, in which case it
         is 20 bytes and jumps to the u32 stored at +16;
  stop   at any address outside the program image.

Record format is `avsp_anim_script.h`; the decode here mirrors
`avsp_anim_read_pose` and `avsp_anim_next_address` exactly.

Outputs
  * generated/avsp_anim_records.h - the span data (git-ignored, contains bytes
    from the program image and must never be committed)
  * data/avsp_anim_records.json   - tracked manifest: counts, address ranges and
    hashes only, no record bytes

Deterministic: two runs over the same inputs produce identical output, which
`--verify-deterministic` checks.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER_DEFAULT = ROOT / "generated" / "avsp_anim_records.h"
MANIFEST_DEFAULT = ROOT / "data" / "avsp_anim_records.json"

WORKRAM_FIRST = 0xFF8000
WORKRAM_SIZE = 0x8000
ACTOR_STRIDE = 0xC0
ACTOR_GRID_ANCHOR = 0xFF8380

RECORD_BYTES = 16
JUMP_RECORD_BYTES = 20
SPAN_JOIN_GAP = 8   # runs closer than this are merged rather than split


def u16(b: bytes, o: int) -> int:
    return (b[o] << 8) | b[o + 1]


def u32(b: bytes, o: int) -> int:
    return int.from_bytes(b[o:o + 4], "big")


def seeds_from_capture(path: Path, rom_len: int) -> set:
    raw = path.read_bytes()
    out = set()
    for f in range(len(raw) // WORKRAM_SIZE):
        s = raw[f * WORKRAM_SIZE:(f + 1) * WORKRAM_SIZE]
        addr = ACTOR_GRID_ANCHOR
        while addr + ACTOR_STRIDE <= WORKRAM_FIRST + WORKRAM_SIZE:
            o = addr - WORKRAM_FIRST
            if s[o] != 0:
                rec = int.from_bytes(s[o + 0x1C:o + 0x20], "big")
                if 0 < rec and rec + JUMP_RECORD_BYTES <= rom_len:
                    out.add(rec)
            addr += ACTOR_STRIDE
    return out


def walk(rom: bytes, seeds: set) -> dict:
    """Reachable records, address -> byte length. Mirrors the C interpreter."""
    sizes: dict[int, int] = {}
    stack = sorted(seeds)
    while stack:
        a = stack.pop()
        if a in sizes or a + JUMP_RECORD_BYTES > len(rom):
            continue
        flags = u16(rom, a + 2)
        is_jump = (flags & 0x8000) != 0
        sizes[a] = JUMP_RECORD_BYTES if is_jump else RECORD_BYTES
        nxt = u32(rom, a + 16) if is_jump else a + 16
        if 0 < nxt and nxt + JUMP_RECORD_BYTES <= len(rom) and nxt not in sizes:
            stack.append(nxt)
    return sizes


def to_spans(sizes: dict) -> list:
    spans = []
    addrs = sorted(sizes)
    if not addrs:
        return spans
    start = addrs[0]
    end = addrs[0] + sizes[addrs[0]]
    for a in addrs[1:]:
        if a <= end + SPAN_JOIN_GAP:
            end = max(end, a + sizes[a])
        else:
            spans.append((start, end))
            start, end = a, a + sizes[a]
    spans.append((start, end))
    return spans


def emit_header(rom: bytes, spans: list, path: Path) -> None:
    lines = [
        "/* Generated by tools/gen_avsp_anim_records.py. Do not edit, do not commit.",
        " * Contains bytes from the private program image. */",
        "#ifndef AVSP_ANIM_RECORDS_H",
        "#define AVSP_ANIM_RECORDS_H",
        "",
        '#include "../avsp_anim_script.h"',
        "",
    ]
    for i, (s, e) in enumerate(spans):
        blob = rom[s:e]
        lines.append("static const unsigned char avsp_anim_span_%02d[%d] = {" % (i, len(blob)))
        for k in range(0, len(blob), 16):
            lines.append("    " + ",".join("0x%02x" % c for c in blob[k:k + 16]) + ",")
        lines.append("};")
    lines.append("")
    lines.append("static const AvspAnimSpan avsp_anim_spans[%d] = {" % len(spans))
    for i, (s, e) in enumerate(spans):
        lines.append("    { 0x%06xu, %du, avsp_anim_span_%02d }," % (s, e - s, i))
    lines.append("};")
    lines.append("static const unsigned int avsp_anim_span_count = %du;" % len(spans))
    lines.append("")
    lines.append("#endif /* AVSP_ANIM_RECORDS_H */")
    lines.append("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))


def build(rom_path: Path, captures: list) -> tuple:
    rom = rom_path.read_bytes()
    seeds = set()
    capture_info = []
    for c in captures:
        p = Path(c)
        s = seeds_from_capture(p, len(rom))
        seeds |= s
        capture_info.append({
            "path": str(p).replace("\\", "/"),
            "sha256": hashlib.sha256(p.read_bytes()).hexdigest(),
            "distinct_seed_pointers": len(s),
        })
    sizes = walk(rom, seeds)
    spans = to_spans(sizes)
    manifest = {
        "schema": 1,
        "classification": "animation-record extraction manifest - addresses and counts only, no record bytes",
        "method": "reachability walk from every observed actor +0x1C, following the script's own control flow",
        "record_format": "16 bytes, advancing to +16; 20 bytes and jumping to the u32 at +16 when flags bit 15 is set",
        "evidence": "DECODED",
        "inputs": {
            "program_image": {
                "path": str(rom_path).replace("\\", "/"),
                "sha256": hashlib.sha256(rom).hexdigest(),
                "bytes": len(rom),
            },
            "captures": capture_info,
        },
        "seed_pointers": len(seeds),
        "reachable_records": len(sizes),
        "record_bytes": sum(sizes.values()),
        "span_count": len(spans),
        "span_bytes": sum(e - s for s, e in spans),
        "address_low": "0x%06x" % min(sizes) if sizes else None,
        "address_high": "0x%06x" % (max(sizes) + sizes[max(sizes)]) if sizes else None,
        "spans": [{"base": "0x%06x" % s, "bytes": e - s} for s, e in spans],
    }
    return rom, spans, manifest


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--rom", required=True)
    ap.add_argument("--capture", required=True, action="append",
                    help="work-RAM capture supplying seed pointers; repeatable")
    ap.add_argument("--header", default=str(HEADER_DEFAULT))
    ap.add_argument("--manifest", default=str(MANIFEST_DEFAULT))
    ap.add_argument("--verify-deterministic", action="store_true")
    args = ap.parse_args()

    rom, spans, manifest = build(Path(args.rom), args.capture)
    text = json.dumps(manifest, indent=1, sort_keys=True) + "\n"

    if args.verify_deterministic:
        _, spans2, manifest2 = build(Path(args.rom), args.capture)
        again = json.dumps(manifest2, indent=1, sort_keys=True) + "\n"
        if again != text or spans2 != spans:
            print("NON-DETERMINISTIC: two extractions differ")
            return 2
        print("deterministic: two extractions agree")

    emit_header(rom, spans, Path(args.header))
    out = Path(args.manifest)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print("wrote %s" % args.header)
    print("wrote %s (sha256=%s)" % (out, hashlib.sha256(text.encode()).hexdigest()))
    print("records=%d spans=%d bytes=%d (%.1f KB)" % (
        manifest["reachable_records"], manifest["span_count"],
        manifest["span_bytes"], manifest["span_bytes"] / 1024.0))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
